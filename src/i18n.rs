pub const CODES: [&str; 8] = ["fr", "en", "es", "de", "it", "pt", "zh", "ja"];
pub const NAMES: [&str; 8] = [
    "Français",
    "English",
    "Español",
    "Deutsch",
    "Italiano",
    "Português (Brasil)",
    "简体中文",
    "日本語",
];
pub fn language(code: &str) -> usize {
    let prefix = code.split(['-', '_']).next().unwrap_or("en");
    CODES.iter().position(|s| *s == prefix).unwrap_or(1)
}
pub fn tr(key: &str, lang: usize) -> &str {
    TEXTS
        .iter()
        .find(|r| r[0] == key)
        .map_or(key, |r| r[lang.min(7)])
}
